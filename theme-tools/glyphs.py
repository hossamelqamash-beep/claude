# Dotless i, used as the base for accented i.
GLYPHS["ı"] = g(2, ".##.. ..#.. ..#.. ..#.. .###.")
GLYPHS["Ç"] = g(0, ".###. #...# #.... #.... #.... #...# .###. ..#.. .##..")
GLYPHS["ç"] = g(2, ".###. #.... #.... #...# .###. ..#.. .##..")


def _compose():
    for ch, (base, accent) in COMPOSED.items():
        top, rows = GLYPHS[base]
        upper, lower = ACCENTS[accent]
        if top == 0:  # capital: accent sits in rows -2..-1
            GLYPHS[ch] = (-2, list(upper) + list(rows))
        else:  # lowercase with x-height starting on row 2
            GLYPHS[ch] = (0, list(lower) + list(rows))


_compose()


def pixels(ch):
    """Yield (col, row) ink pixels for a character, rows relative to cap top."""
    if ch not in GLYPHS:
        ch = "□"
    top, rows = GLYPHS[ch]
    for r, line in enumerate(rows):
        for c, v in enumerate(line):
            if v == "#":
                yield c, top + r


def check():
    for ch, (top, rows) in GLYPHS.items():
        for line in rows:
            assert len(line) == CELL_W, (ch, line)
        assert top >= -2 and top + len(rows) <= CAP + DESCENT, ch


check()
